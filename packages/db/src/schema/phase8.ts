import { index, integer, sqliteTable, text, uniqueIndex } from "drizzle-orm/sqlite-core";

// Mirrors migrations/0014_zim.sql (docs/data-model.md "Phase 8 as built"). sources.zim_package_id is added in sources.ts.

export const zimPackages = sqliteTable(
  "zim_packages",
  {
    id: integer("id").primaryKey({ autoIncrement: true }),
    publicId: text("public_id").notNull().unique(),
    name: text("name").notNull(),
    title: text("title").notNull(),
    description: text("description"),
    language: text("language"),
    creator: text("creator"),
    publisher: text("publisher"),
    date: text("date"),
    flavour: text("flavour"),
    tags: text("tags"),
    uuid: text("uuid").notNull().unique(),
    volumeId: integer("volume_id"),
    storageMode: text("storage_mode", { enum: ["in_place", "copied"] }).notNull(),
    filePath: text("file_path").notNull(),
    relativePath: text("relative_path"),
    sizeBytes: integer("size_bytes").notNull(),
    checksumSha256: text("checksum_sha256"),
    checksumState: text("checksum_state", { enum: ["pending", "done", "failed"] }).notNull().default("pending"),
    articleCount: integer("article_count").notNull().default(0),
    mediaCount: integer("media_count").notNull().default(0),
    entryCount: integer("entry_count").notNull().default(0),
    hasFulltextIndex: integer("has_fulltext_index").notNull(),
    hasTitleIndex: integer("has_title_index").notNull(),
    newNamespaceScheme: integer("new_namespace_scheme").notNull(),
    mainPath: text("main_path"),
    hasIllustration: integer("has_illustration").notNull().default(0),
    sourceUrl: text("source_url"),
    licenseName: text("license_name"),
    licenseUrl: text("license_url"),
    attributionText: text("attribution_text"),
    priority: integer("priority").notNull().default(1),
    enabledForSearch: integer("enabled_for_search").notNull().default(1),
    state: text("state", { enum: ["importing", "ready", "degraded", "missing", "removing"] }).notNull(),
    stateDetail: text("state_detail"),
    importedAt: integer("imported_at").notNull(),
    lastVerifiedAt: integer("last_verified_at"),
    updatedAt: integer("updated_at").notNull(),
  },
  (t) => [index("zim_packages_state_idx").on(t.state), index("zim_packages_language_idx").on(t.language), uniqueIndex("zim_packages_path_uq").on(t.filePath)],
);
